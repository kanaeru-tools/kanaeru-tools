// 「対象外」は決算振替の「損益」や「諸口」など、決算書に載せない科目
export type PlKubun = (typeof PL_KUBUN)[number];
export type BsKubun = (typeof BS_KUBUN)[number];
export type Kubun = PlKubun | BsKubun | "対象外";

// 収益の区分は貸方がプラス、それ以外の PL の区分は借方がプラス
export const CREDIT_POSITIVE: ReadonlySet<Kubun> = new Set<Kubun>(["売上高", "営業外収益", "特別利益"]);

export function isPl(k: Kubun): k is PlKubun {
  return (PL_KUBUN as readonly string[]).includes(k);
}

export interface AccountRule {
  kubun: Kubun;
  // 会社によって区分が分かれやすい科目。確認画面で目立たせる
  check?: boolean;
}

export type AccountMap = Record<string, AccountRule>;

const A = (kubun: Kubun, names: string[], check = false): AccountMap =>
  Object.fromEntries(names.map((n) => [n, check ? { kubun, check } : { kubun }]));

