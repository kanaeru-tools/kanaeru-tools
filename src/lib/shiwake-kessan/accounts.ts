// 科目名の表記ゆれ（前後の空白・全角空白）だけ吸収する。似た名前への自動の当てはめはしない
export function normalizeAccount(name: string): string {
  return name.replace(/[\s　]+/g, "");
}

export function lookupAccount(name: string, map: AccountMap): AccountRule | undefined {
  return map[name] ?? map[normalizeAccount(name)];
}
